#!/usr/bin/env node
// Regenerates packages/shared/src/bnaLabels.ts from rosetta-candidate-search's RCS_EBL table.
// Usage: node scripts/gen-bna-labels.mjs <path to rosetta-candidate-search>
import { readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const rcs = resolve(process.argv[2] ?? "../rosetta-candidate-search");
const csvPath = resolve(rcs, "ebl_for_rcs_v1.0_20260722/rcs_ready/bna_name_candidates.csv");
const out = resolve(dirname(fileURLToPath(import.meta.url)), "../packages/shared/src/bnaLabels.ts");

/** Minimal RFC 4180 line parser (no embedded newlines in this table). */
const splitCsvLine = (line) => {
  const out = [];
  let cur = "";
  let quoted = false;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (quoted) {
      if (c === '"' && line[i + 1] === '"') (cur += '"'), i++;
      else if (c === '"') quoted = false;
      else cur += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") out.push(cur), (cur = "");
    else cur += c;
  }
  out.push(cur);
  return out;
};

const [header, ...lines] = readFileSync(csvPath, "utf8").trim().split(/\r?\n/);
const cols = splitCsvLine(header);
const at = (name) => {
  const i = cols.indexOf(name);
  if (i < 0) throw new Error(`column ${name} not found`);
  return i;
};
const areas = new Map();
for (const line of lines) {
  const f = splitCsvLine(line);
  const get = (name) => f[at(name)];
  const l = Number(get("bna_label_id_l"));
  const r = Number(get("bna_label_id_r"));
  if (!l || r !== l + 1) throw new Error(`unexpected label pair in: ${line}`);
  areas.set(l, [l, get("bna_area_abbr"), get("bna_l2_abbr"), get("bna_area_name")]);
}
if (areas.size !== 123) throw new Error(`expected 123 BNA areas, found ${areas.size}`);

let commit = "unknown";
try {
  commit = execFileSync("git", ["-C", rcs, "rev-parse", "--short", "HEAD"], { encoding: "utf8" }).trim();
} catch {}

const rows = [...areas.values()].sort((a, b) => a[0] - b[0]).map((a) => `  ${JSON.stringify(a)},`);
writeFileSync(
  out,
  `// Generated by scripts/gen-bna-labels.mjs from rosetta-candidate-search ${commit}
// (ebl_for_rcs_v1.0_20260722/rcs_ready/bna_name_candidates.csv). Do not edit by hand.

/** Brainnetome Atlas areas: [left label ID (odd; right = +1), official area abbreviation, L2 (gyrus) abbreviation, area name]. */
export const BNA_AREAS: ReadonlyArray<readonly [number, string, string, string]> = [
${rows.join("\n")}
];
`,
);
console.log(`wrote ${out} (${areas.size} areas)`);
